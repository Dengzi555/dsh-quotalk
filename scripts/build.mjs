import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url),read=path=>readFile(new URL(path,root),'utf8');
const [bridge,core,store,selection,sidebar]=await Promise.all(['src/bridge.js','src/core.js','src/store.js','src/selection.js','src/sidebar.js'].map(read));
const result=`// Generated by npm run build. React and layout come from DSH.
window.__ModuleLoader__.load({id:'dsh-quotalk',factory(require){
const React=require('react'),globalThis={};
${core}
${bridge}
${store}
${selection}
${sidebar}
return {inject:['slots','uiSession','sidebarRight','sidebarRightTabs'],apply(ctx){
 const core=globalThis.MarginCore,stores=new Map();
 const storeFor=sessionId=>{if(!sessionId)throw new Error('请先打开 DSH 对话。');if(!stores.has(sessionId))stores.set(sessionId,createSessionStore(ctx,sessionId,core));return stores.get(sessionId);};
 const menu=installSelectionMenu(ctx,core,selection=>{
   const store=storeFor(selection.sessionId);store.select(selection);ctx.sidebarRight.openTab('quotalk');
 });
 const {Toolbar,Sidebar}=createComponents(React,menu,storeFor);
 ctx.effect(()=>()=>{menu.dispose();for(const store of stores.values())store.dispose();stores.clear();},'quotalk lifecycle');
 let previous=ctx.uiSession.adapter.current.getSnapshot()?.props?.sessionId;
 ctx.effect(()=>ctx.uiSession.adapter.current.subscribe(()=>{const current=ctx.uiSession.adapter.current.getSnapshot()?.props?.sessionId;if(current!==previous){stores.get(previous)?.cancelAll();previous=current;}}),'quotalk session isolation');
 ctx.effect(()=>ctx.sidebarRightTabs.register({id:'dsh-quotalk',kind:'quotalk',priority:'extension',title:()=> '追问',keepMounted:false}),'quotalk sidebar type');
 ctx.slots.inject('shell.overlay',()=>ctx.slots.register({name:'shell.overlay',id:'dsh-quotalk-selection',order:50},Toolbar));
 ctx.slots.inject('sidebar.right.pane.tab',()=>ctx.slots.register({name:'sidebar.right.pane.tab',key:'dsh-quotalk'},Sidebar));
}};
}});
`;
await mkdir(new URL('lib/',root),{recursive:true});await writeFile(new URL('lib/client.js',root),result);
console.log('Built native selection toolbar and sidebar ('+Buffer.byteLength(result)+' bytes).');
